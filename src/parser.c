static inline bool sym__first_character_set_1(int32_t c) {
  return (c < '?'
    ? (c < '/'
      ? (c < '*'
        ? (c >= '!' && c <= '%')
        : c <= '+')
      : (c <= '/' || c == '='))
    : (c <= '?' || (c < 'a'
      ? (c < '_'
        ? (c >= 'A' && c <= 'Z')
        : c <= '_')
      : (c <= 'z' || c == '~'))));
}

static inline bool sym__first_character_set_2(int32_t c) {
  return (c < '?'
    ? (c < '*'
      ? (c < '%'
        ? c == '!'
        : c <= '%')
      : (c <= '+' || (c < '='
        ? (c >= '-' && c <= '/')
        : c <= '=')))
    : (c <= '?' || (c < 'a'
      ? (c < '_'
        ? (c >= 'A' && c <= 'Z')
        : c <= '_')
      : (c <= 'z' || c == '~'))));
}

